CREATE TABLE IF NOT EXISTS menu_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE COLLATE NOCASE,
 description TEXT DEFAULT '', category TEXT NOT NULL, price REAL NOT NULL CHECK (price >= 0),
 available INTEGER NOT NULL DEFAULT 1 CHECK (available IN (0, 1)), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY AUTOINCREMENT, full_name TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
 password_hash TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS orders (
 id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, customer_name TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','completed','cancelled')),
 total REAL NOT NULL DEFAULT 0 CHECK (total >= 0), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS order_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT, order_id INTEGER NOT NULL, menu_item_id INTEGER NOT NULL,
 item_name TEXT NOT NULL, unit_price REAL NOT NULL CHECK (unit_price >= 0),
 quantity INTEGER NOT NULL CHECK (quantity > 0), line_total REAL NOT NULL CHECK (line_total >= 0),
 FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE);
